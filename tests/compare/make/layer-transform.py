# 1. layer-transform: position, size, rotation, scale; the corner squares show which way is up and right
w = Wallpaper('layer-transform', 'layer transforms')
w.solid('top left red', 100, HEIGHT - 100, 120, 120, '1 0 0')
w.solid('top right green', WIDTH - 100, HEIGHT - 100, 120, 120, '0 1 0')
w.solid('bottom left blue', 100, 100, 120, 120, '0 0 1')
w.solid('bottom right yellow', WIDTH - 100, 100, 120, 120, '1 1 0')
w.solid('plain', 400, 540, 200, 200, '1 1 1')
w.solid('rotated 45', 800, 540, 200, 200, '1 0.5 0', angle=45)
w.solid('bar rotated 90', 1200, 540, 360, 80, '0 1 1', angle=90)
w.solid('scaled 2 x 0.5', 1600, 540, 100, 100, '1 0 1', scale='2 0.5 1')
w.solid('bar rotated 30', 560, 840, 400, 50, '0.8 0.8 0.8', angle=30)
w.solid('bar rotated -30', 1360, 840, 400, 50, '0.8 0.8 0.8', angle=-30)
w.solid('tiny', 960, 200, 6, 6, '1 1 1')
w.save()
